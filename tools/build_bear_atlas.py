"""
Pack the Djungelskog bear animation frames used by the web app into a single
WebP atlas (one row per state, 192x208 cells, native pixels).

    .venv/bin/python tools/build_bear_atlas.py

Writes web/src/assets/bear/bear-atlas.webp and web/src/game/bearAtlas.ts.
"""

import glob
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art/djungelskog-pixel/frames")
OUT_IMG = os.path.join(ROOT, "web/src/assets/bear/bear-atlas.webp")
OUT_TS = os.path.join(ROOT, "web/src/game/bearAtlas.ts")
W, H, COLS = 192, 208, 8

# atlas name -> source folder ("running" is the paw-to-mouth thinking loop)
STATES = [
    ("idle", "idle"),
    ("wave", "waving"),
    ("jump", "jumping"),
    ("fail", "failed"),
    ("review", "review"),
    ("think", "running"),
    ("wait", "waiting"),
    ("look", "look"),
]


def main():
    rows = []
    for name, folder in STATES:
        frames = sorted(glob.glob(os.path.join(SRC, folder, "*.png")))
        for start in range(0, len(frames), COLS):
            rows.append((name, frames[start:start + COLS]))
    atlas = Image.new("RGBA", (W * COLS, H * len(rows)), (0, 0, 0, 0))
    layout = {}
    for r, (name, frames) in enumerate(rows):
        for c, path in enumerate(frames):
            im = Image.open(path).convert("RGBA")
            assert im.size == (W, H), path
            atlas.paste(im, (c * W, r * H))
            layout.setdefault(name, []).append([c, r])
    os.makedirs(os.path.dirname(OUT_IMG), exist_ok=True)
    # lossy keeps it ~0.5 MB; lossless is ~2 MB for this painterly pixel art
    atlas.save(OUT_IMG, "WEBP", quality=86, alpha_quality=90, method=6)
    with open(OUT_TS, "w") as f:
        f.write("// Generated by tools/build_bear_atlas.py. Do not edit.\n")
        f.write(f"export const BEAR_CELL = {{ w: {W}, h: {H}, cols: {COLS}, rows: {len(rows)} }};\n")
        f.write(f"export const BEAR_FRAMES = {json.dumps(layout, separators=(',', ':'))} as const;\n")
    print(f"{OUT_IMG}: {atlas.size}, {os.path.getsize(OUT_IMG):,} bytes")


if __name__ == "__main__":
    main()
